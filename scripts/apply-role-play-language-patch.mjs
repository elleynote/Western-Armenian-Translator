function replaceOnce(
  input,
  search,
  replacement,
  label,
) {
  const first =
    input.indexOf(search);

  assert.notEqual(
    first,
    -1,
    `${label}: expected source block was not found`,
  );

  assert.equal(
    input.indexOf(
      search,
      first + search.length,
    ),
    -1,
    `${label}: expected source block was not unique`,
  );

  return input.replace(
    search,
    replacement,
  );
}

function replaceOnceRegex(
  input,
  pattern,
  replacement,
  label,
) {
  const matches = [
    ...input.matchAll(
      new RegExp(
        pattern.source,
        `${pattern.flags.replace("g", "")}g`,
      ),
    ),
  ];

  assert.equal(
    matches.length,
    1,
    `${label}: expected exactly one matching source block, found ${matches.length}`,
  );

  return input.replace(
    pattern,
    replacement,
  );
}

function transformSection(
  input,
  startMarker,
  endMarker,
  transform,
  label,
) {
  const start =
    input.indexOf(
      startMarker,
    );

  assert.notEqual(
    start,
    -1,
    `${label}: start marker missing`,
  );

  const end =
    input.indexOf(
      endMarker,
      start + startMarker.length,
    );

  assert.notEqual(
    end,
    -1,
    `${label}: end marker missing`,
  );

  const section =
    input.slice(
      start,
      end,
    );

  const nextSection =
    transform(section);

  assert.notEqual(
    nextSection,
    section,
    `${label}: transform made no changes`,
  );

  return (
    input.slice(0, start) +
    nextSection +
    input.slice(end)
  );
}

